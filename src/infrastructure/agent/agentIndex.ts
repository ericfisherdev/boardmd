import { backlogIssues, findActiveSprint, issuesInSprint } from '../../domain/boardModels';
import { Issue, IssueLinkKind } from '../../domain/issue';
import { IssueGraph } from '../../domain/issueGraph';
import { bySequence, Sprint } from '../../domain/sprint';
import { Workflow } from '../../domain/workflow';
import { BoardLocations } from '../boardLocations';

export const AGENT_INDEX_SCHEMA_VERSION = 1;

export interface AgentIndexInput {
	readonly issues: readonly Issue[];
	readonly sprints: readonly Sprint[];
	readonly workflow: Workflow;
	readonly keyPrefix: string;
	readonly locations: BoardLocations;
}

/** Machine-readable snapshot of the whole board, with relationships resolved in both directions. */
export function buildAgentIndex(input: AgentIndexInput): Record<string, unknown> {
	const { issues, sprints, workflow, locations } = input;
	const graph = new IssueGraph(issues);
	return {
		schema_version: AGENT_INDEX_SCHEMA_VERSION,
		about: `Generated by the BoardMD plugin from the notes of the project "${locations.projectName}" in ${locations.issuesFolder} and ${locations.sprintsFolder}. The notes are the source of truth; see ${locations.agentGuidePath}.`,
		project: locations.projectName,
		key_prefix: input.keyPrefix,
		issues_folder: locations.issuesFolder,
		sprints_folder: locations.sprintsFolder,
		workflow: workflow.statuses.map(({ id, name, category }) => ({ id, name, category })),
		active_sprint: findActiveSprint(sprints)?.name ?? null,
		sprints: [...sprints].sort(bySequence).map((sprint) => sprintEntry(sprint, issues, locations)),
		backlog: backlogIssues(issues, sprints, workflow).map((issue) => issue.key),
		issues: [...issues].sort(byKeyNumber).map((issue) => issueEntry(issue, graph, workflow, locations)),
	};
}

function sprintEntry(sprint: Sprint, issues: readonly Issue[], locations: BoardLocations): Record<string, unknown> {
	return {
		name: sprint.name,
		state: sprint.state,
		sequence: sprint.sequence,
		start_date: sprint.startDate,
		end_date: sprint.endDate,
		goal: sprint.goal,
		committed_points: sprint.committedPoints,
		issues: issuesInSprint(issues, sprint.name).map((issue) => issue.key),
		completed_issues: sprint.outcome?.completedIssues ?? null,
		carried_over_issues: sprint.outcome?.carriedOverIssues ?? null,
		completed_points: sprint.outcome?.completedPoints ?? null,
		note: `${locations.sprintsFolder}/${sprint.name}.md`,
	};
}

function issueEntry(issue: Issue, graph: IssueGraph, workflow: Workflow, locations: BoardLocations): Record<string, unknown> {
	const links = graph.linksOf(issue.key);
	const status = workflow.resolve(issue.status);
	return {
		key: issue.key,
		summary: issue.summary,
		type: issue.type,
		status: status.id,
		status_category: status.category,
		priority: issue.priority,
		points: issue.points,
		sprint: issue.sprint,
		assignee: issue.assignee,
		parent: issue.parent,
		children: graph.childrenOf(issue.key),
		[IssueLinkKind.Blocks]: links[IssueLinkKind.Blocks],
		[IssueLinkKind.BlockedBy]: links[IssueLinkKind.BlockedBy],
		open_blockers: graph.openBlockersOf(issue.key, (statusId) => workflow.isDone(statusId)),
		[IssueLinkKind.RelatesTo]: links[IssueLinkKind.RelatesTo],
		[IssueLinkKind.Duplicates]: links[IssueLinkKind.Duplicates],
		[IssueLinkKind.DuplicatedBy]: links[IssueLinkKind.DuplicatedBy],
		created: issue.created,
		resolved: issue.resolved,
		source: issue.source,
		rank: issue.rank,
		note: `${locations.issuesFolder}/${issue.key}.md`,
	};
}

function byKeyNumber(a: Issue, b: Issue): number {
	return a.key.localeCompare(b.key, undefined, { numeric: true });
}
